const digitsOf = (n) => String(n).split("").map(Number);
const sumDigits = (n) => digitsOf(n).reduce((a, b) => a + b, 0);
function reduce(n) {
  while (n > 9) n = sumDigits(n);
  return n;
}

// 主命數：生日所有數字相加；保留中間的天賦數（兩位數）
function lifeNumber(y, m, d) {
  const all = `${y}${String(m).padStart(2, "0")}${String(d).padStart(2, "0")}`;
  const total = all.split("").map(Number).reduce((a, b) => a + b, 0);
  const steps = [total];
  let n = total;
  while (n > 9) { n = sumDigits(n); steps.push(n); }
  return { digits: all, total, steps, life: n, talent: total };
}

function gridCounts(digitString) {
  const counts = Array(10).fill(0);
  for (const ch of digitString) counts[Number(ch)]++;
  return counts;
}

// 九宮格：生日數字＋天賦數＋主命數都放進格子（台灣常見的做法）
function numerologyChart(y, m, d) {
  const base = lifeNumber(y, m, d);
  const gridDigits = base.digits + String(base.talent) + String(base.life);
  const counts = gridCounts(gridDigits);
  const lines = LINES.filter(([nums]) => nums.every((n) => counts[n] > 0));
  const missing = [1, 2, 3, 4, 5, 6, 7, 8, 9].filter((n) => counts[n] === 0);
  const strong = [1, 2, 3, 4, 5, 6, 7, 8, 9].filter((n) => counts[n] >= 3);
  const now = new Date();
  const yearNum = reduce(m + d + sumDigits(now.getFullYear()));
  const months = Array.from({ length: 12 }, (_, i) => reduce(yearNum + i + 1));
  const masters = [11, 22, 33].filter((x) => base.steps.includes(x));
  return { ...base, counts, lines, missing, strong, yearNum, months, masters, year: now.getFullYear(), gridDigits };
}

